export async function initAdminRulesView(state) {
  const container = document.getElementById('rules-table-container');
  if (!container) return;

  const refreshBtn = document.getElementById('btn-refresh-rules');
  if (refreshBtn) {
    refreshBtn.addEventListener('click', () => initAdminRulesView(state));
  }

  try {
    const rules = await api.getRules();
    renderRulesTable(rules, state);
  } catch (err) {
    console.error('Failed to load rules:', err);
    container.innerHTML = `
      <div style="padding: var(--space-6); text-align: center; color: var(--color-red-600);">
        <p style="font-weight: 600;">Failed to load regulatory rules: ${escapeHtml(err.message)}</p>
      </div>
    `;
  }
}

function renderRulesTable(rules, state) {
  const container = document.getElementById('rules-table-container');
  if (!container) return;

  const user = state.getCurrentUser() || {};
  const isAdmin = user.role === 'ADMIN';

  if (!rules || rules.length === 0) {
    container.innerHTML = `
      <div style="padding: var(--space-6); text-align: center; color: var(--text-muted);">
        No regulatory rules found in engine database.
      </div>
    `;
    return;
  }

  container.innerHTML = `
    <div class="table-responsive">
      <table class="data-table">
        <thead>
          <tr>
            <th>Rule Code</th>
            <th>Rule Title & Category</th>
            <th>Official Statutory Citation</th>
            <th>Version & Parameters</th>
            <th>Verification Status</th>
            <th>Execution State</th>
            ${isAdmin ? '<th>Governance Actions</th>' : ''}
          </tr>
        </thead>
        <tbody>
          ${rules.map(rule => {
            const v = rule.active_version || (rule.versions && rule.versions[0]) || {};
            const isApproved = rule.status === 'APPROVED_FOR_PROTOTYPE_USE';
            const isActive = rule.is_active;

            return `
              <tr>
                <td style="font-family: var(--font-mono); font-weight: 600; color: var(--color-blue-700); white-space: nowrap;">
                  ${escapeHtml(rule.rule_code)}
                </td>
                <td>
                  <div style="font-weight: 600; color: var(--text-primary);">${escapeHtml(rule.title)}</div>
                  <div style="font-size: 11px; color: var(--text-muted); text-transform: uppercase;">
                    ${escapeHtml((rule.category || '').replace(/_/g, ' '))}
                  </div>
                </td>
                <td style="font-size: var(--text-xs); color: var(--text-secondary); max-width: 260px; line-height: 1.4;">
                  ${escapeHtml(rule.official_source)}
                </td>
                <td style="font-size: var(--text-xs); font-family: var(--font-mono);">
                  <div>v${v.version_number || 1} • <span class="badge ${v.severity === 'DEFICIENCY' ? 'badge-danger' : 'badge-warning'}">${v.severity || 'DEFICIENCY'}</span></div>
                  <div style="color: var(--text-muted); font-size: 10px; margin-top: 2px;">
                    ${escapeHtml(v.recommended_action ? (v.recommended_action.substring(0, 45) + '...') : '')}
                  </div>
                </td>
                <td>
                  <span class="badge ${isApproved ? 'badge-success' : 'badge-warning'}">
                    ${isApproved ? 'VERIFIED' : 'DRAFT'}
                  </span>
                </td>
                <td>
                  <span class="badge ${isActive ? 'badge-success' : 'badge-secondary'}">
                    ${isActive ? 'ACTIVE' : 'INACTIVE'}
                  </span>
                </td>
                ${isAdmin ? `
                  <td>
                    ${!isActive ? `
                      <button class="btn btn-secondary btn-sm btn-activate-rule" data-code="${escapeHtml(rule.rule_code)}" title="Authorize rule for automated evaluation">
                        ${icons.check}
                        <span>Activate</span>
                      </button>
                    ` : `
                      <span style="font-size: 11px; color: var(--color-green-700); font-weight: 500;">Enforceable</span>
                    `}
                  </td>
                ` : ''}
              </tr>
            `;
          }).join('')}
        </tbody>
      </table>
    </div>
  `;

  // Bind Admin Activation Buttons
  if (isAdmin) {
    container.querySelectorAll('.btn-activate-rule').forEach(btn => {
      btn.addEventListener('click', async () => {
        const code = btn.getAttribute('data-code');
        btn.disabled = true;
        btn.textContent = 'Activating...';
        try {
          await api.activateRule(code);
          await initAdminRulesView(state);
        } catch (err) {
          alert(`Failed to activate rule ${code}: ${err.message}`);
          btn.disabled = false;
          btn.textContent = 'Activate';
        }
      });
    });
  }
}

function escapeHtml(str) {
  if (!str) return '';
  return String(str).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}
